import { BusinessRuleViolation } from "../../shared/errors/business-error.js";
import { ErrorCode } from "../../shared/enums/error-code.enum.js";

/** Maximum accepted length for a SKU and a variant name. */
const SKU_MAX_LENGTH = 64;
const NAME_MAX_LENGTH = 100;

/** Complete state of a product variant, used to restore it from persistence. */
export interface VariantSnapshot {
  /** Internal autoincremental identifier. Null until persisted. */
  id: number | null;
  /** Public identifier (UUID v7). Unique and immutable. */
  publicId: string;
  /** Internal identifier of the owning product. */
  productId: number;
  coverImageId: number | null;
  /** Unique, immutable and never reused once assigned. */
  sku: string;
  name: string;
  /** Own production cost in currency units. Null when unknown. */
  unitCost: number | null;
  /** Net (pre-tax) sale price in currency units, greater than zero. */
  unitPrice: number;
  /** Display order, greater than or equal to one. */
  sortOrder: number;
  /**
   * Physical stock units. Owned by the (future) inventory module: catalog
   * procedures never write it, they only read it for public availability.
   */
  existenciaFisica: number;
  isActive: boolean;
  isDeleted: boolean;
}

/** Data required to create a new variant. The SKU is generated by the use case. */
export interface NewVariantData {
  publicId: string;
  productId: number;
  coverImageId?: number | null;
  sku: string;
  name: string;
  unitCost: number | null;
  unitPrice: number;
  sortOrder: number;
  /** Activation is decided by the use case. */
  isActive: boolean;
}

/** Data that can be changed on an existing variant. */
export interface UpdateVariantData {
  name: string;
  unitCost: number | null;
  unitPrice: number;
  sortOrder: number;
}

/**
 * Product variant entity. Every modification goes through methods that enforce
 * business rules. Taxes are never computed inside the entity; the use case
 * derives tax-inclusive prices with the TaxCalculator.
 */
export class Variant {
  private state: VariantSnapshot;

  private constructor(state: VariantSnapshot) {
    this.state = state;
  }

  /** Creates a new variant. The SKU must already be generated by the use case. */
  static create(data: NewVariantData): Variant {
    return new Variant({
      id: null,
      publicId: data.publicId,
      productId: Variant.requireProductId(data.productId),
      coverImageId: data.coverImageId == null ? null : Variant.requireProductId(data.coverImageId),
      sku: Variant.requireSku(data.sku),
      name: Variant.requireName(data.name),
      unitCost: Variant.requireUnitCost(data.unitCost),
      unitPrice: Variant.requireUnitPrice(data.unitPrice),
      sortOrder: Variant.requireSortOrder(data.sortOrder),
      // New variants start with zero stock; the inventory module maintains it.
      existenciaFisica: 0,
      isActive: data.isActive,
      isDeleted: false,
    });
  }

  /** Restores the entity from its persisted state, without revalidating. */
  static restore(snapshot: VariantSnapshot): Variant {
    return new Variant({ ...snapshot });
  }

  get id(): number | null {
    return this.state.id;
  }

  get publicId(): string {
    return this.state.publicId;
  }

  get productId(): number {
    return this.state.productId;
  }

  get sku(): string {
    return this.state.sku;
  }

  get name(): string {
    return this.state.name;
  }

  get unitCost(): number | null {
    return this.state.unitCost;
  }

  get unitPrice(): number {
    return this.state.unitPrice;
  }

  get sortOrder(): number {
    return this.state.sortOrder;
  }

  get isActive(): boolean {
    return this.state.isActive;
  }

  get isDeleted(): boolean {
    return this.state.isDeleted;
  }

  assignCover(imageId: number | null, productIsActive: boolean): void {
    this.assertNotDeleted();
    if (imageId !== null) Variant.requirePositiveInteger(imageId, "imageId");
    if (imageId === null && productIsActive && this.state.isActive) {
      throw new BusinessRuleViolation("An active variant of an active product must have a cover image", ErrorCode.INVALID_CATALOG_ENTITY_STATE, undefined, undefined);
    }
    this.state.coverImageId = imageId;
  }

  /** Replaces the mutable commercial data. SKU and product are immutable. */
  update(data: UpdateVariantData): void {
    this.assertNotDeleted();
    this.state.name = Variant.requireName(data.name);
    this.state.unitCost = Variant.requireUnitCost(data.unitCost);
    this.state.unitPrice = Variant.requireUnitPrice(data.unitPrice);
    this.state.sortOrder = Variant.requireSortOrder(data.sortOrder);
  }

  /** Activates the variant. */
  activate(): void {
    this.assertNotDeleted();
    this.state.isActive = true;
  }

  /** Deactivates the variant without removing it. */
  deactivate(): void {
    this.assertNotDeleted();
    this.state.isActive = false;
  }

  /** Soft delete: marks it as deleted and also deactivates it. The SKU stays reserved. */
  markDeleted(): void {
    this.assertNotDeleted();
    this.state.isDeleted = true;
    this.state.isActive = false;
  }

  /** Copy of the current state. */
  toSnapshot(): VariantSnapshot {
    return { ...this.state };
  }

  private assertNotDeleted(): void {
    if (this.state.isDeleted) {
      throw new BusinessRuleViolation(
        "The product variant was deleted",
        ErrorCode.INVALID_CATALOG_ENTITY_STATE,
        undefined,
        undefined,
      );
    }
  }

  private static requireProductId(value: number): number {
    Variant.requirePositiveInteger(value, "productId");
    return value;
  }

  private static requireSku(value: string): string {
    const trimmed = value.trim();
    if (trimmed.length === 0) {
      throw new BusinessRuleViolation(
        "The required field sku was not provided",
        ErrorCode.REQUIRED_FIELD_MISSING,
        "sku",
        undefined,
      );
    }
    if (trimmed.length > SKU_MAX_LENGTH) {
      throw new BusinessRuleViolation(
        `The SKU exceeds ${SKU_MAX_LENGTH} characters`,
        ErrorCode.INVALID_INPUT,
        "sku",
        undefined,
      );
    }
    return trimmed;
  }

  private static requireName(value: string): string {
    const trimmed = value.trim();
    if (trimmed.length === 0) {
      throw new BusinessRuleViolation(
        "The required field name was not provided",
        ErrorCode.REQUIRED_FIELD_MISSING,
        "name",
        undefined,
      );
    }
    if (trimmed.length > NAME_MAX_LENGTH) {
      throw new BusinessRuleViolation(
        `The variant name exceeds ${NAME_MAX_LENGTH} characters`,
        ErrorCode.INVALID_INPUT,
        "name",
        undefined,
      );
    }
    return trimmed;
  }

  private static requireUnitCost(value: number | null): number | null {
    if (value === null) {
      return null;
    }
    if (!Number.isFinite(value) || value < 0) {
      throw new BusinessRuleViolation(
        "The unit cost must be null or greater than or equal to zero",
        ErrorCode.INVALID_INPUT,
        "unitCost",
        undefined,
      );
    }
    return value;
  }

  private static requireUnitPrice(value: number): number {
    if (!Number.isFinite(value) || value <= 0) {
      throw new BusinessRuleViolation(
        "The unit price must be greater than zero",
        ErrorCode.INVALID_INPUT,
        "unitPrice",
        undefined,
      );
    }
    return value;
  }

  private static requireSortOrder(value: number): number {
    Variant.requirePositiveInteger(value, "sortOrder");
    return value;
  }

  private static requirePositiveInteger(value: number, field: string): void {
    if (!Number.isInteger(value) || value < 1) {
      throw new BusinessRuleViolation(
        `The field ${field} must be an integer greater than zero`,
        ErrorCode.INVALID_INPUT,
        field,
        undefined,
      );
    }
  }
}
