import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import { isAbsolute, join } from "node:path";
import { BusinessRuleViolation } from "../../domain/shared/errors/business-error.js";
import { ErrorCode } from "../../domain/shared/enums/error-code.enum.js";
import type { ImageStorage } from "../../domain/shared/interfaces/providers/image-storage.js";

/** Resolves the physical file of a key inside the storage directory. */
function pathOf(directory: string, key: string): string {
  if (key.length === 0 || key.includes("/") || key.includes("\\") || key.includes("..")) {
    throw new BusinessRuleViolation(
      "The storage key must be a plain file name without path separators",
      ErrorCode.INVALID_INPUT,
      key === "" ? "storageKey" : key,
      undefined,
    );
  }
  return join(directory, key);
}

/**
 * Binary image storage kept on the local filesystem.
 *
 * Keys are generated by the application (UUID v7 + ".webp"), so only the
 * plain-file-name shape is enforced here; no physical path is ever returned.
 * The concrete directory is provided by configuration (stage 5 wiring).
 */
export class LocalImageStorage implements ImageStorage {
  constructor(private readonly directory: string) {
    if (!isAbsolute(directory)) {
      throw new BusinessRuleViolation(
        "The image storage directory must be an absolute path",
        ErrorCode.INVALID_INPUT,
        undefined,
        undefined,
      );
    }
  }

  async save(key: string, content: Buffer): Promise<void> {
    const target = pathOf(this.directory, key);
    await mkdir(this.directory, { recursive: true });
    await writeFile(target, content);
  }

  async read(key: string): Promise<Buffer | null> {
    const target = pathOf(this.directory, key);
    try {
      return await readFile(target);
    } catch (error: unknown) {
      if (isMissingFileError(error)) {
        return null;
      }
      throw error;
    }
  }

  async delete(key: string): Promise<void> {
    const target = pathOf(this.directory, key);
    try {
      await unlink(target);
    } catch (error: unknown) {
      // Deleting a missing file keeps the delete idempotent.
      if (!isMissingFileError(error)) {
        throw error;
      }
    }
  }
}

/** Distinguishes an ENOENT failure from any other filesystem error. */
function isMissingFileError(error: unknown): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    "code" in error &&
    error.code === "ENOENT"
  );
}
